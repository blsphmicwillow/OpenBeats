export const DEFAULT_THEME = THEMES[0];

export function themeById(id: string, custom?: Theme): Theme {
  if (id === 'custom' && custom) return custom;
  return THEMES.find((t) => t.id === id) ?? THEMES[0];
}

/** CSS custom properties consumed by styles.css. */
export function themeVars(theme: Theme, accentOverride: string | null): Record<string, string> {
  const accent = accentOverride ?? theme.accent;
  return {
    '--bg': theme.bg,
    '--panel': theme.panel,
    '--panel2': theme.panel2,
    '--panel3': theme.panel3,
    '--border': theme.border,
    '--text': theme.text,
    '--dim': theme.dim,
    '--accent': accent,
    '--accent-text': theme.accentText,
    '--playhead': theme.playhead,
    '--selection': theme.selection,
    '--scheme': theme.dark ? 'dark' : 'light',
    '--clip-text': theme.dark ? '#ffffff' : '#14140f',
  };
}
